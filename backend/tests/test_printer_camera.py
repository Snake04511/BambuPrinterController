    assert part == b"--frame\r\nContent-Type: image/jpeg\r\nContent-Length: 4\r\n\r\n\xff\xd8xx\r\n"
    assert MJPEG_CONTENT_TYPE == "multipart/x-mixed-replace; boundary=frame"


