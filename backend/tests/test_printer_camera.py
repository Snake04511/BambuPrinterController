CODE = "12345678"


def tiny_jpeg(color: tuple[int, int, int]) -> bytes:
    buf = io.BytesIO()
    Image.new("RGB", (8, 8), color).save(buf, "JPEG", quality=70)
    return buf.getvalue()


FRAMES = [tiny_jpeg((255, 0, 0)), tiny_jpeg((0, 255, 0)), tiny_jpeg((0, 0, 255))]


@pytest.fixture(scope="session")
def cert(tmp_path_factory: pytest.TempPathFactory) -> tuple[str, str]:
    d = tmp_path_factory.mktemp("cert")
    crt, key = d / "c.pem", d / "k.pem"
    subprocess.run(
        ["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", str(key), "-out", str(crt),
         "-days", "1", "-subj", "/CN=fake-p1s"],
        check=True, capture_output=True,
    )
    return str(crt), str(key)


class FakeCamera:
    """Minimal port-6000 chamber camera: checks the 80-byte login, then streams frames."""

    def __init__(self, cert: tuple[str, str], *, code: str = CODE, interval: float = 0.03,
                 drop_after: int | None = None, silent_on_bad_code: bool = False) -> None:
        self.ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        self.ctx.load_cert_chain(*cert)
        self.code = code
        self.interval = interval
        self.drop_after = drop_after
        self.silent_on_bad_code = silent_on_bad_code
        self.connections = 0
        self.active = 0
        self.max_active = 0
        self.auth_ok = 0
        self.auth_bad = 0
        self.packets: list[bytes] = []
        self.conn_times: list[float] = []
        self.server: asyncio.Server | None = None
        self.port = 0
        self._handlers: set[asyncio.Task[Any]] = set()

    async def start(self, port: int = 0) -> FakeCamera:
        self.server = await asyncio.start_server(self._handle, "127.0.0.1", port, ssl=self.ctx)
        self.port = self.server.sockets[0].getsockname()[1]
        return self

    async def stop(self) -> None:
        assert self.server is not None
        self.server.close()
        for t in list(self._handlers):
            t.cancel()
        await asyncio.gather(*self._handlers, return_exceptions=True)
        await self.server.wait_closed()

    async def _handle(self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        task = asyncio.current_task()
        assert task is not None
        self._handlers.add(task)
        self.connections += 1
        self.conn_times.append(time.monotonic())
        self.active += 1
        self.max_active = max(self.max_active, self.active)
        try:
            pkt = await asyncio.wait_for(reader.readexactly(80), 5)
            self.packets.append(pkt)
            magic, cmd, pad, user, code = struct.unpack("<II8s32s32s", pkt)
            good = (magic, cmd, pad, user.rstrip(b"\0"), code.rstrip(b"\0")) == (
                0x40, 0x3000, b"\0" * 8, b"bblp", self.code.encode())
            if not good:
                self.auth_bad += 1
                if self.silent_on_bad_code:
                    await asyncio.sleep(30)
                return
            self.auth_ok += 1
            i = 0
            while self.drop_after is None or i < self.drop_after:
                jpg = FRAMES[i % len(FRAMES)]
                header = struct.pack("<IIII", len(jpg), 0, 1, 0)
                writer.write(header + jpg)
                await writer.drain()
                i += 1
                await asyncio.sleep(self.interval)
        except (asyncio.IncompleteReadError, ConnectionError, ssl.SSLError, TimeoutError):
            pass
        finally:
            self.active -= 1
            writer.close()
            try:
                await asyncio.wait_for(writer.wait_closed(), 1)
            except BaseException:  # noqa: BLE001
                writer.transport.abort()
            self._handlers.discard(task)


def make_cam(srv: FakeCamera, code: str = CODE, **kw: Any) -> PrinterCamera:
    opts: dict[str, Any] = dict(idle_grace=0.3, connect_timeout=2.0, first_frame_timeout=1.0,
                                read_timeout=1.0, backoff_min=0.05, backoff_max=0.2, auth_backoff=0.5)
    opts.update(kw)
    return PrinterCamera("127.0.0.1", lambda: code, port=srv.port, **opts)


async def until(cond: Callable[[], bool], timeout: float = 3.0) -> None:
    loop = asyncio.get_running_loop()
    end = loop.time() + timeout
    while not cond():
        if loop.time() > end:
            raise AssertionError("condition not met in time")
        await asyncio.sleep(0.02)


def run(cert: tuple[str, str], body: Callable[..., Awaitable[None]], **srv_kw: Any) -> None:
    async def main() -> None:
        srv = await FakeCamera(cert, **srv_kw).start()
        try:
            await body(srv)
        finally:
            await srv.stop()

    asyncio.run(asyncio.wait_for(main(), 20))


