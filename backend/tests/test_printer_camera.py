def test_mjpeg_release_on_disconnect_and_reaper(cert: tuple[str, str]) -> None:
    async def body(srv: FakeCamera) -> None:
        cam = make_cam(srv, stream_lease_ttl=0.3)
        try:
            # Client disconnect = the server cancels the task iterating the generator.
            gen = cam.mjpeg(fps=20)

            async def pump() -> None:
                async for _ in gen:
                    pass

            t = asyncio.create_task(pump())
            await until(lambda: cam.status()["frames"] >= 2)
            assert cam.status()["demand"] == {"viewer": 1}
            t.cancel()
            await asyncio.gather(t, return_exceptions=True)
            # Cancellation alone must release the lease (checked BEFORE aclose(); the
            # earlier version closed the generator first, so it proved nothing).
            assert cam.status()["demand"] == {}
            await gen.aclose()

            # Abandoned generator (never closed, never pulled again) is reaped by TTL.
            it, _, _ = await cam.open_stream(fps=20)
            assert it is not None
            await it.__anext__()  # type: ignore[union-attr]
            assert cam.status()["demand"] == {"viewer": 1}
            await until(lambda: cam.status()["demand"] == {}, 2)
            await until(lambda: srv.active == 0, 2)  # then the idle close follows
            with pytest.raises(StopAsyncIteration):
                await it.__anext__()  # type: ignore[union-attr]
        finally:
            await cam.aclose()

    run(cert, body)


