def test_auth_packet_layout() -> None:
    pkt = build_auth_packet("abc")
    assert len(pkt) == 80
    assert pkt[0:4] == b"\x40\0\0\0"
    assert pkt[4:8] == b"\0\x30\0\0"
    assert pkt[8:16] == b"\0" * 8
    assert pkt[16:48] == b"bblp".ljust(32, b"\0")
    assert pkt[48:80] == b"abc".ljust(32, b"\0")


