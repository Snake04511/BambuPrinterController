def test_snapshot_and_cache(cert: tuple[str, str]) -> None:
    async def body(srv: FakeCamera) -> None:
        cam = make_cam(srv)
        try:
            jpg, err = await cam.snapshot()
            assert err == "" and jpg in FRAMES
            assert srv.packets[0] == build_auth_packet(CODE)
            st = cam.status()
            assert st["connected"] and st["last_error"] == "" and st["last_frame_age"] < 1
            # Within max_age: served from the buffer, same connection.
            jpg2, err2 = await cam.snapshot(max_age=5)
            assert jpg2 and not err2 and srv.connections == 1
            await asyncio.sleep(0.3)
            assert cam.fps() > 5
        finally:
            await cam.aclose()

    run(cert, body)


def test_fanout_two_consumers_one_connection(cert: tuple[str, str]) -> None:
    async def body(srv: FakeCamera) -> None:
        cam = make_cam(srv)
        try:
            async def consume(n: int) -> list[bytes]:
                it, ctype, err = await cam.open_stream(fps=30)
                assert it is not None and ctype == MJPEG_CONTENT_TYPE and err == ""
                parts: list[bytes] = []
                async for chunk in it:  # type: ignore[union-attr]
                    parts.append(chunk)
                    if len(parts) >= n:
                        break
                await it.aclose()  # type: ignore[union-attr]
                return parts

            a, b = await asyncio.gather(consume(5), consume(5))
            for parts in (a, b):
                assert len(parts) == 5
                for p in parts:
                    assert p.startswith(b"--frame\r\nContent-Type: image/jpeg\r\n")
                    body_ = p.split(b"\r\n\r\n", 1)[1][:-2]
                    assert body_ in FRAMES
            assert srv.connections == 1 and srv.max_active == 1
            assert cam.status()["demand"] == {}
        finally:
            await cam.aclose()

    run(cert, body)


def test_idle_close_and_reopen(cert: tuple[str, str]) -> None:
    async def body(srv: FakeCamera) -> None:
        cam = make_cam(srv, idle_grace=0.3)
        try:
            async with cam.demand("timelapse"):
                await until(lambda: cam.status()["connected"])
                assert cam.status()["demand"] == {"timelapse": 1}
            await asyncio.sleep(0.1)
            assert cam.status()["connected"], "grace period should keep the socket"
            await until(lambda: srv.active == 0 and not cam.status()["connected"], 2)
            assert cam.status()["state"] == "idle"
            # Demand returns -> new connection, never two at once.
            jpg, err = await cam.snapshot(max_age=0)
            assert jpg and not err
            assert srv.connections == 2 and srv.max_active == 1
        finally:
            await cam.aclose()
        await until(lambda: srv.active == 0)

    run(cert, body)


